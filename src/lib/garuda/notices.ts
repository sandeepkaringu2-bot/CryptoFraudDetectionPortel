import { inr, usdt } from "./format";
import { KNOWN_VASPS } from "./registry";
import type { Endpoint } from "./types";

export function noticeId(complaintId: string, wallet: string): string {
  const seed = `${complaintId}:${wallet}`.replace(/[^A-Za-z0-9]/g, "").slice(-10).toUpperCase();
  return `GARUDA-FZ-${seed}`;
}

/**
 * SAHYOG-style emergency asset preservation draft (English).
 * Officer must review, sign, and transmit via official nodal / SAHYOG channel.
 * Not an automated legal filing.
 */
export function freezeNoticeEn(opts: {
  officerId: string;
  complaintId: string;
  sourceWallet: string;
  endpoint: Endpoint;
  station?: string;
}): string {
  const v = KNOWN_VASPS[opts.endpoint.wallet];
  const id = noticeId(opts.complaintId, opts.endpoint.wallet);
  const sla = v?.freezeSlaHours ?? 6;
  const station = opts.station ? ` / ${opts.station}` : "";
  return [
    "INDIAN CYBER CRIME COORDINATION CENTRE (I4C)",
    "Ministry of Home Affairs — CIS Division",
    "SAHYOG / Emergency Asset Preservation Request",
    "",
    `Notice ID: ${id}`,
    `Date: ${new Date().toLocaleString("en-IN", { timeZone: "Asia/Kolkata" })} IST`,
    `From: ${opts.officerId}${station}`,
    `To: ${v?.nodal ?? "Nodal Officer"}, ${opts.endpoint.entity}`,
    `Channel: ${v?.contact ?? "registered nodal desk"}`,
    `Reference SLA (exchange-published): ${sla} hour(s)`,
    "",
    `Subject: Immediate freeze of crypto assets linked to NCRP ${opts.complaintId}`,
    "",
    "Legal basis",
    "1. Section 91, Code of Criminal Procedure, 1973 — production and preservation of documents and electronic records.",
    "2. Section 17, Prevention of Money Laundering Act, 2002 — attachment and freeze of proceeds of crime.",
    "3. Information Technology Act, 2000 — duty to preserve digital evidence and subscriber information.",
    "4. Applicable I4C / MHA advisories on crypto-asset tracing for law-enforcement agencies.",
    "",
    "Facts (machine-traced; to be officer-verified before service)",
    `A victim-reported wallet ${opts.sourceWallet} was walked by the GARUDA attribution engine.`,
    `Endpoint cluster / deposit address ${opts.endpoint.wallet} is attributed to ${opts.endpoint.entity} (${opts.endpoint.kind}).`,
    `Value observed at this sink: ${usdt(opts.endpoint.amountUsdt)} (≈ ${inr(opts.endpoint.amountUsdt)}).`,
    `Hop distance from the reported wallet: ${opts.endpoint.hops}. Risk score: ${opts.endpoint.risk}/100.`,
    `Recoverable flag (Indian VASP / rails): ${opts.endpoint.recoverable ? "YES — priority freeze target" : "NO — still preserve records"}.`,
    "",
    "You are requested to act IMMEDIATELY, and in any event within four (4) hours of receipt:",
    "a) Freeze crypto balances held against this cluster and any co-attributed deposit addresses, and freeze linked INR / bank / UPI rails where under your control;",
    "b) Preserve KYC, CKYC, video-KYC, registered mobile / email, login IPs, device fingerprints, order books, deposit tags, and internal transfer logs for a minimum of 180 days;",
    "c) Restrict withdrawals, P2P completion, internal shuttling, and off-platform transfers for a minimum of 72 hours or until written release by the requesting authority;",
    "d) Acknowledge this notice in writing with a freeze confirmation reference to the requesting officer.",
    "",
    "Failure to preserve records after receipt of this notice may attract consequences under the PMLA and the IT Act.",
    "",
    "Disclaimer: This document is a draft statutory communication generated by GARUDA for I4C investigative use.",
    "It must be reviewed and signed by an authorised officer and served only through SAHYOG or the registered nodal channel of the VASP.",
    "It does not by itself constitute a court order or FIU-IND direction.",
  ].join("\n");
}

